"""Build local SVG technology tiles and the README section, without dependencies.

Run: python scripts/generate_tech_stack.py
Source icons and their licenses are vendored in assets/tech-stack/.
"""

import json
from html import escape
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "tech-stack"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)
ET.register_namespace("xlink", "http://www.w3.org/1999/xlink")


def icon_content(identifier):
    root = ET.fromstring((ASSETS / "source" / f"{identifier}.svg").read_text(encoding="utf-8-sig"))
    for parent in list(root.iter()):
        for child in list(parent):
            if child.tag.split("}")[-1] in ("metadata", "namedview", "title", "desc"):
                parent.remove(child)
    for element in root.iter():
        if element.tag.split("}")[-1] in ("script", "foreignObject"):
            raise ValueError("Unexpected active SVG content")
        for key, value in element.attrib.items():
            if key.split("}")[-1] == "href" and not value.startswith("#"):
                raise ValueError("Technology tiles must not load external resources")
    # Devicon's monochrome marks need light fills on a dark tile.
    if identifier in ("github", "apachekafka", "tableau"):
        color = "#e0efff" if identifier != "tableau" else "#8fc5ff"
        root.set("fill", color)
        for element in root.iter():
            if element.get("fill", "").lower() in ("#181616", "#231f20", "#000", "#000000", "black"):
                element.set("fill", color)
    if "viewBox" not in root.attrib:
        width = float(re.sub(r"[^0-9.]", "", root.get("width", "128")))
        height = float(re.sub(r"[^0-9.]", "", root.get("height", "128")))
        root.set("viewBox", f"0 0 {width:g} {height:g}")
    root.attrib.update({"x": "25", "y": "15", "width": "42", "height": "42"})
    return ET.tostring(root, encoding="unicode")


def make_tile(item):
    name = escape(item["label"])
    # The .NET Core source uses transparent letter cutouts inside its circle.
    underlay = '<circle cx="46" cy="36" r="20.5" fill="#f5efff"/>' if item["id"] == "dotnetcore" else ""
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="92" height="96" '
        'viewBox="0 0 92 96" role="img" aria-labelledby="title">'
        f'<title id="title">{name}</title>'
        '<rect x="14" y="4" width="64" height="64" rx="14" fill="#162640" stroke="#294367"/>'
        f'{underlay}'
        f'{icon_content(item["id"])}'
        f'<text x="46" y="86" text-anchor="middle" fill="#b9d3ee" '
        f'font-family="Segoe UI,Arial,sans-serif" font-size="10.5">{name}</text>'
        '</svg>\n'
    )


def main():
    groups = json.loads((ASSETS / "stack.json").read_text(encoding="utf-8"))
    lines = ['<!-- TECH STACK: generated by scripts/generate_tech_stack.py -->']
    total = 0
    for group in groups:
        lines.extend(["", f'### {group["title"]}', "", "<p>"])
        for item in group["items"]:
            tile = make_tile(item)
            ET.fromstring(tile)
            (ASSETS / f'{item["id"]}.svg').write_text(tile, encoding="utf-8")
            name = escape(item["label"], quote=True)
            lines.append(f'  <img src="assets/tech-stack/{item["id"]}.svg" alt="{name}" title="{name}" width="92" height="96" />')
            total += 1
        lines.append("</p>")
    lines.extend(["", '<sub>Icons: <a href="assets/tech-stack/SOURCES.md">sources &amp; credits</a>.</sub>',
                  '<!-- /TECH STACK -->'])
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8-sig")
    start = text.index("<!-- TECH STACK:")
    end = text.index("<!-- /TECH STACK -->", start) + len("<!-- /TECH STACK -->")
    readme.write_text(text[:start] + "\n".join(lines) + text[end:], encoding="utf-8")
    print(f"Generated and parsed {total} SVG tiles in {len(groups)} groups.")


if __name__ == "__main__":
    main()
